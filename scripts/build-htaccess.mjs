/**
 * Writes dist/.htaccess from the redirect map (redirects.mjs) and the set of
 * pre-rendered pages found in dist/_pages. Runs last in the post-build chain
 * so every generated page (site pages, articles, course OG pages) gets its
 * explicit rewrite rule - no filesystem probing on the server, no directory
 * slash surprises. Apache/LiteSpeed compatible (Hostinger runs LiteSpeed).
 */
import fs from "node:fs";
import path from "node:path";
import { DIST, SPA_PREFIXES } from "./site-routes.mjs";
import { EXACT, PATTERNS, GONE } from "./redirects.mjs";

const esc = (s) => s.replace(/[.+?^${}()|[\]\\]/g, "\\$&");

export function listPrerenderedPages() {
  const base = path.join(DIST, "_pages");
  if (!fs.existsSync(base)) return [];
  const out = [];
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name.endsWith(".html")) {
        const rel = path.relative(base, full).replace(/\\/g, "/").replace(/\.html$/, "");
        out.push(rel === "index" ? "/" : `/${rel}`);
      }
    }
  };
  walk(base);
  return out.sort();
}

export function buildHtaccess(pages) {
  const L = [];
  L.push("# Generated by scripts/build-htaccess.mjs at build time - do not edit on the server.");
  L.push("# Source of truth: scripts/redirects.mjs (redirects) + dist/_pages (pre-rendered pages).");
  L.push("Options -Indexes");
  L.push("");
  L.push("<IfModule mod_rewrite.c>");
  L.push("RewriteEngine On");
  L.push("RewriteBase /");
  L.push("");
  L.push("# http->https and www->apex are redirected by Hostinger's edge before requests reach here.");
  L.push("");
  L.push("# 1. Old WordPress URLs -> their new homes (exact)");
  for (const [from, to] of EXACT) {
    const flags = to.includes("#") ? "[R=301,NE,L]" : "[R=301,L]";
    L.push(`RewriteRule ^${esc(from.replace(/^\//, ""))}/?$ ${to} ${flags}`);
  }
  L.push("");
  L.push("# 2. Old WordPress URL families + the app's former /p/ prefix (patterns)");
  for (const [src, to] of PATTERNS) {
    const flags = to.includes("#") ? "[R=301,NE,L]" : "[R=301,L]";
    L.push(`RewriteRule ^${src}/?$ ${to} ${flags}`);
  }
  L.push("");
  L.push("# 3. WordPress internals are gone for good");
  for (const src of GONE) L.push(`RewriteRule ^${src}$ - [G,L]`);
  L.push("");
  L.push("# 4. No trailing slashes on pages (real directories such as /media/ are left alone)");
  L.push("RewriteCond %{REQUEST_FILENAME} !-d");
  L.push("RewriteRule ^(.+)/$ /$1 [R=301,L]");
  L.push("");
  L.push("# 5. Direct hits on the pre-rendered files go to their clean URL");
  L.push("RewriteCond %{THE_REQUEST} \\s/_pages/");
  L.push("RewriteRule ^_pages/index\\.html$ / [R=301,L]");
  L.push("RewriteCond %{THE_REQUEST} \\s/_pages/");
  L.push("RewriteRule ^_pages/(.+)\\.html$ /$1 [R=301,L]");
  L.push("");
  L.push("# 6. Pre-rendered pages (real HTML for people, search engines and AI crawlers)");
  L.push("RewriteRule ^$ _pages/index.html [L]");
  for (const p of pages) {
    if (p === "/") continue;
    const rel = p.replace(/^\//, "");
    L.push(`RewriteRule ^${esc(rel)}$ _pages/${rel}.html [L]`);
  }
  L.push("");
  L.push("# 7. Client-rendered areas (sign-in, courses, admin) get the app shell");
  L.push(`RewriteRule ^(${SPA_PREFIXES.map(esc).join("|")})(/|$) index.html [L]`);
  L.push("</IfModule>");
  L.push("");
  L.push("# Everything else that is not a real file is a real 404 (and 410s share the page)");
  L.push("ErrorDocument 404 /404.html");
  L.push("ErrorDocument 410 /404.html");
  L.push("");
  L.push("<IfModule mod_headers.c>");
  L.push('  Header always set X-Content-Type-Options "nosniff"');
  L.push('  Header always set Referrer-Policy "strict-origin-when-cross-origin"');
  L.push('  Header always set X-Frame-Options "SAMEORIGIN"');
  L.push('  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"');
  L.push('  Header always set Strict-Transport-Security "max-age=31536000"');
  L.push('  <FilesMatch "\\.html$">');
  L.push('    Header set Cache-Control "no-cache, must-revalidate"');
  L.push("  </FilesMatch>");
  L.push('  <FilesMatch "\\.(js|css|woff2?)$">');
  L.push('    Header set Cache-Control "public, max-age=31536000, immutable"');
  L.push("  </FilesMatch>");
  L.push('  <FilesMatch "\\.(png|jpe?g|webp|svg|ico|gif|mp4)$">');
  L.push('    Header set Cache-Control "public, max-age=604800"');
  L.push("  </FilesMatch>");
  L.push('  <FilesMatch "\\.(xml|txt)$">');
  L.push('    Header set Cache-Control "public, max-age=3600"');
  L.push("  </FilesMatch>");
  L.push("</IfModule>");
  L.push("");
  return L.join("\n");
}

export function writeHtaccess() {
  const pages = listPrerenderedPages();
  const out = buildHtaccess(pages);
  fs.writeFileSync(path.join(DIST, ".htaccess"), out);
  console.log(`.htaccess written: ${EXACT.length} exact + ${PATTERNS.length} pattern redirects, ${pages.length} page rules`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  writeHtaccess();
}
